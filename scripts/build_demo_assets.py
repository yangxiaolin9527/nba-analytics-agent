"""Bundle archived replay records for the file-openable demo; no providers run."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.demo_routes import AGENT_REPORT_PATH, LIVE_AGENT_REPORT_PATH, STATIC_PATH, _agent_report, _agent_replay_cases, _catalog


def build_bundle() -> dict:
    records = {item['case_id']: item for item in _agent_report()['cases']}
    live_records = {}
    if LIVE_AGENT_REPORT_PATH.exists():
        live_records = {item['case_id']: item for item in _agent_report(LIVE_AGENT_REPORT_PATH)['cases']}
    agent = []
    for item in _agent_replay_cases():
        is_live = item['source_type'] == 'live_provider'
        record = (live_records if is_live else records)[item['case_id']]
        path = LIVE_AGENT_REPORT_PATH if is_live else AGENT_REPORT_PATH
        agent.append({**item, 'response': record.get('response', {}), 'provenance': {
            'source_type': item['source_type'], 'report': str(path.relative_to(ROOT)),
        }})
    return {'stats': _catalog(), 'agent': agent}


def main() -> None:
    bundle = build_bundle()
    content = json.dumps(bundle, ensure_ascii=False, separators=(',', ':'))
    (STATIC_PATH / 'demo-data.js').write_text(
        '// Generated by scripts/build_demo_assets.py from archived replay records.\n'
        + 'window.NBA_DEMO_DATA = ' + content + ';\n', encoding='utf-8')
    print(f'Bundled {len(bundle["stats"]["cases"])} structured and {len(bundle["agent"])} agent replays.')


if __name__ == '__main__':
    main()
